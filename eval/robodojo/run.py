SHIM_MARKER = "# Generated by Magic-W0 eval/robodojo/run.py"


def conda_command(environment: str | None, command: list[str]) -> list[str]:
    if not environment:
        return command
    selector = "--prefix" if "/" in environment else "--name"
    return ["conda", "run", "--no-capture-output", selector, environment, *command]


def simulator_shim(root: Path, *, install: bool, policy_name: str = "Magic_W0") -> Path:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", policy_name):
        raise ValueError("policy-name must be a Python module name")
    target = root / "XPolicyLab/policy" / policy_name
    allowed = {"__init__.py", "deploy.py", "deploy.yml", "__pycache__"}
    if target.exists():
        foreign = [p.name for p in target.iterdir() if p.name not in allowed]
        deploy = target / "deploy.py"
        if (
            foreign
            or not deploy.is_file()
            or not deploy.read_text().startswith(SHIM_MARKER)
        ):
            raise FileExistsError(
                f"Existing policy at {target}; move it aside before installing the local adapter"
            )
    if install:
        target.mkdir(parents=True, exist_ok=True)
        (target / "__init__.py").write_text(SHIM_MARKER + "\n")
        (target / "deploy.py").write_text(
            SHIM_MARKER
            + "\nfrom eval.robodojo.deploy import eval_one_episode, eval_one_episode_batch\n"
        )
    return target


def free_port(host: str) -> int:
    with socket.socket() as sock:
        sock.bind((host, 0))
        return int(sock.getsockname()[1])


def check_port_available(host: str, port: int):
    with socket.socket() as sock:
        try:
            sock.bind((host, port))
        except OSError as exc:
            raise RuntimeError(
                f"Policy port {host}:{port} is already occupied or unavailable"
            ) from exc


async def _websocket_probe(host: str, port: int, timeout: float):
    from websockets.asyncio.client import connect

    async with connect(
        f"ws://{host}:{port}", open_timeout=timeout, close_timeout=timeout
    ) as connection:
        pong = await connection.ping()
        await asyncio.wait_for(pong, timeout)


def wait_ready(
    process: subprocess.Popen,
    host: str,
    port: int,
    timeout: float,
    *,
    ready_file: Path,
    run_id: str,
):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise RuntimeError(
                f"Policy server exited with status {process.returncode}; see policy.log"
            )
        if ready_file.is_file():
            record = json.loads(ready_file.read_text())
            if (
                record.get("run_id") != run_id
                or record.get("url") != f"ws://{host}:{port}"
            ):
                raise RuntimeError("Policy readiness record does not match this run")
            # The child writes the run-specific record only after it binds.
            # Verify the transport too; a listening TCP port alone isn't enough.
            asyncio.run(
                _websocket_probe(
                    host, port, min(2, max(0.01, deadline - time.monotonic()))
                )
            )
            if process.poll() is not None:
                raise RuntimeError("Policy server exited during readiness check")
            return
        time.sleep(min(0.1, max(0, deadline - time.monotonic())))
    raise TimeoutError(f"Policy server did not become ready within {timeout:g}s")


def stop_process(process: subprocess.Popen | None, *, grace_seconds: float = 10):
    if process is None:
        return
    # Kill the group, including conda and shell grandchildren.
    try:
        os.killpg(process.pid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    deadline = time.monotonic() + grace_seconds
    while True:
        process.poll()  # Reap the leader, but continue checking descendants.
        try:
            os.killpg(process.pid, 0)
        except ProcessLookupError:
            break
        if time.monotonic() >= deadline:
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            break
        time.sleep(0.05)
    process.wait(timeout=5)


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--task", required=True)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--robodojo-root", type=Path)
    p.add_argument("--config", type=Path, default=REPO_ROOT / "configs/robodojo.yaml")
    p.add_argument("--checkpoint", type=Path)
    p.add_argument("--vlm-assets", type=Path)
    p.add_argument("--policy-gpu", default="0")
    p.add_argument("--env-gpu", default="1")
    p.add_argument(
        "--policy-env", help="Conda name or prefix; defaults to current Python"
    )
    p.add_argument("--sim-env", default="RoboDojo")
    p.add_argument(
        "--policy-name", default="Magic_W0", help="Name of the simulator import shim"
    )
    p.add_argument(
        "--env-config", help="External RoboDojo env_cfg name; defaults to YAML setting"
    )
    p.add_argument("--port", type=int)
    p.add_argument(
        "--episodes", type=int, help="Cap RoboDojo evaluation episodes using EVAL_NUM"
    )
    p.add_argument("--startup-timeout", type=float, default=1200)
    p.add_argument("--output-dir", type=Path, default=REPO_ROOT / "runs/robodojo")
    p.add_argument(
        "--dry-run",
        action="store_true",
        help="Show commands without writing or starting processes",
    )
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    if not re.fullmatch(r"[A-Za-z0-9_-]+", args.task) or args.startup_timeout <= 0:
        raise ValueError(
            "task must be a benchmark task name and startup-timeout must be positive"
        )
    if not args.env_gpu.isdigit() or not args.policy_gpu.isdigit():
        raise ValueError("policy-gpu and env-gpu must each name one numeric GPU index")
    cfg = yaml.safe_load(args.config.read_text())
    if args.episodes is not None and args.episodes < 1:
        raise ValueError("episodes must be positive")
    if args.robodojo_root:
        cfg["robodojo_root"] = str(args.robodojo_root)
    root = resolve_robodojo_root(cfg)
    if args.checkpoint:
        cfg["checkpoint_path"] = str(args.checkpoint)
    if args.vlm_assets:
        cfg["vlm_checkpoint"] = str(args.vlm_assets)
    if args.env_config:
        cfg["env_cfg_type"] = args.env_config
    cfg.update(
        task_name=args.task,
        seed=args.seed,
        robodojo_root=str(root),
        host="127.0.0.1",
        port=args.port
        if args.port is not None
        else (19000 if args.dry_run else free_port("127.0.0.1")),
        protocol="ws",
        policy_name=args.policy_name,
    )
    if not 1 <= cfg["port"] <= 65535:
        raise ValueError("port must be in 1..65535")
    cfg["checkpoint_path"] = str(_resolve_path(cfg["checkpoint_path"]))
    cfg["vlm_checkpoint"] = str(_resolve_path(cfg["vlm_checkpoint"]))
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    output = args.output_dir.resolve() / f"{args.task}-seed{args.seed}-{stamp}"
    config_path = output / "resolved.yaml"
    policy = conda_command(
        args.policy_env,
        [
            "python" if args.policy_env else sys.executable,
            "-m",
            "eval.robodojo.server",
            "--config",
            str(config_path),
        ],
    )
    sim = conda_command(
        args.sim_env,
        [
            "bash",
            str(root / "scripts/eval_policy.sh"),
            "--task_name",
            args.task,
            "--env_cfg_type",
            str(cfg["env_cfg_type"]),
            "--policy_name",
            args.policy_name,
            "--host",
            cfg["host"],
            "--port",
            str(cfg["port"]),
            "--protocol",
            "ws",
            "--eval_batch",
            str(bool(cfg["eval_batch"])).lower(),
            "--root_dir",
            str(root),
            "--device_id",
            args.env_gpu,
            "--additional_info",
            f"magic_w0_run={stamp}",
            "--seed",
            str(args.seed),
        ],
    )
    print("Policy:", shlex.join(policy), flush=True)
    print("Simulator:", shlex.join(sim), flush=True)
    print(
        f"Policy CUDA_VISIBLE_DEVICES={args.policy_gpu}; simulator CUDA_VISIBLE_DEVICES={args.env_gpu}",
        flush=True,
    )
    if args.dry_run:
        print(
            "Dry run: commands only; resources and simulator compatibility are not checked."
        )
        return 0
    check_port_available(cfg["host"], cfg["port"])
    bootstrap(root)
    resolve_checkpoint(cfg)
    from magic_w0.config import MagicW0Config

    MagicW0Config(vlm_checkpoint=cfg["vlm_checkpoint"]).validate_checkpoint_layout()
    shim = simulator_shim(root, install=False, policy_name=args.policy_name)
    output.mkdir(parents=True, exist_ok=False)
    cfg["run_id"] = uuid.uuid4().hex
    cfg["ready_file"] = str(output / "ready.json")
    config_path.write_text(yaml.safe_dump(cfg, sort_keys=False))
    simulator_shim(root, install=True, policy_name=args.policy_name)
    (shim / "deploy.yml").write_text(yaml.safe_dump(cfg, sort_keys=False))
    env = dict(os.environ)
    if args.episodes is not None:
        env["EVAL_NUM"] = str(args.episodes)
    paths = [
        str(REPO_ROOT),
        str(REPO_ROOT / "src"),
        str(root),
        str(root / "XPolicyLab"),
    ]
    env["PYTHONPATH"] = os.pathsep.join(
        paths + ([env["PYTHONPATH"]] if env.get("PYTHONPATH") else [])
    )
    summary = {
        "task": args.task,
        "seed": args.seed,
        "config": str(config_path),
        "policy_command": policy,
        "simulator_command": sim,
        "status": "failed",
    }
    server = client = None

    def terminate(_signal, _frame):
        raise KeyboardInterrupt("Evaluation terminated")

    previous_handler = signal.signal(signal.SIGTERM, terminate)
    try:
        with (output / "policy.log").open("w") as log:
            server = subprocess.Popen(
                policy,
                cwd=REPO_ROOT,
                env={**env, "CUDA_VISIBLE_DEVICES": args.policy_gpu},
                stdout=log,
                stderr=subprocess.STDOUT,
                start_new_session=True,
            )
            wait_ready(
                server,
                cfg["host"],
                cfg["port"],
                args.startup_timeout,
                ready_file=Path(cfg["ready_file"]),
                run_id=cfg["run_id"],
            )
            with (output / "simulator.log").open("w") as sim_log:
                client = subprocess.Popen(
                    sim,
                    cwd=root,
                    env={**env, "CUDA_VISIBLE_DEVICES": args.env_gpu},
                    stdout=sim_log,
                    stderr=subprocess.STDOUT,
                    start_new_session=True,
                )
                while client.poll() is None:
                    if server.poll() is not None:
                        raise RuntimeError(
                            "Policy server exited during simulation; see policy.log"
                        )
                    time.sleep(1)
                summary["simulator_exit_code"] = client.returncode
                if client.returncode:
                    raise RuntimeError(
                        f"Simulator failed with status {client.returncode}; see simulator.log"
                    )
                summary["status"] = "completed"
    except BaseException as exc:
        summary["error"] = str(exc)
        raise
    finally:
        signal.signal(signal.SIGTERM, signal.SIG_IGN)
        stop_process(client)
        stop_process(server)
        signal.signal(signal.SIGTERM, previous_handler)
        (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
        print(f"Logs and execution summary: {output}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
